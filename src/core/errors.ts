export type SecurityErrorCode = (typeof SECURITY_ERROR_CODES)[number] | (string & {});

export class SecurityError extends Error {
  public override readonly name = 'SecurityError';
  public readonly code: SecurityErrorCode;
  public readonly status: number;

  constructor(code: SecurityErrorCode, status: number = 403) {
    super(code);
    this.code = code;
    this.status = status;
    Object.setPrototypeOf(this, new.target.prototype);
  }
}

export function isSecurityError(err: unknown): err is SecurityError {
  return err instanceof Error && (err as SecurityError).name === 'SecurityError';
}
