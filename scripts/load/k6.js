// Device fixture array generated by seed-load.ts mounted at /fixtures/devices.json
const fixtures = new SharedArray('devices', function () {
  return JSON.parse(open('/fixtures/devices.json'));
});

// Fixed body and SHA-256 hash computed once at script initialization
const RAW_BODY = '{"benchmark":true}';
const BODY_HASH = crypto.sha256(RAW_BODY, 'hex');

// Target endpoint configuration
const BASE_URL = __ENV.BASE_URL || 'http://api:3000';
const TARGET_URL = `${BASE_URL}/api/tarot/read`;
const REQUEST_TARGET = '/api/tarot/read';

// Sequence base offset between stages (e.g. 1e9*n as canonical decimal) to guarantee strict monotonicity
function parseSequenceBase() {
  const raw = __ENV.SEQUENCE_BASE;
  if (raw === undefined || raw === '') return 0n;
  if (!/^(0|[1-9]\d*)$/.test(raw)) {
    throw new Error(`Invalid SEQUENCE_BASE: "${raw}" (must be a canonical decimal integer)`);
  }
  return BigInt(raw);
}
const baseSequence = parseSequenceBase();

/**
 * Converts IEEE P1363 (64-byte raw r||s) signature to strict ASN.1 DER ECDSA format.
 * Structure: SEQUENCE { r INTEGER, s INTEGER } (length <= 72 bytes).
 */
function p1363ToDer(rawSig) {
  if (!(rawSig instanceof Uint8Array) || rawSig.byteLength !== 64) {
    throw new Error(`Invalid raw ECDSA P-256 signature length: ${rawSig?.byteLength ?? 'unknown'} (expected exactly 64 bytes)`);
  }

  const r = rawSig.subarray(0, 32);
  const s = rawSig.subarray(32, 64);

  function encodeDerInteger(bytes) {
    let start = 0;
    while (start < bytes.length - 1 && bytes[start] === 0) {
      start++;
    }
    const val = bytes.subarray(start);
    const needsZero = (val[0] & 0x80) !== 0;
    const len = val.length + (needsZero ? 1 : 0);
    const out = new Uint8Array(2 + len);
    out[0] = 0x02; // INTEGER tag
    out[1] = len;
    if (needsZero) {
      out[2] = 0x00;
      out.set(val, 3);
    } else {
      out.set(val, 2);
    }
    return out;
  }

  const rDer = encodeDerInteger(r);
  const sDer = encodeDerInteger(s);
  const totalLen = rDer.length + sDer.length;
  const out = new Uint8Array(2 + totalLen);
  out[0] = 0x30; // SEQUENCE tag
  out[1] = totalLen;
  out.set(rDer, 2);
  out.set(sDer, 2 + rDer.length);
  return out;
}

// Per-VU cached CryptoKey and DeviceId (each VU is an isolated JS VM and makes serial requests)
let cachedKey = null;
let cachedDeviceId = null;

export default async function () {
  // 1. One unique key per exec.vu.idInTest - 1 (1-based index); strictly reject overflow (no modulo wrapping)
  if (!cachedKey) {
    const vuId = exec.vu.idInTest;
    const vuIndex = vuId - 1;
    if (vuIndex < 0 || vuIndex >= fixtures.length) {
      throw new Error(`Insufficient device fixtures: VU ID ${vuId} exceeds total fixtures (${fixtures.length}). Modulo wrapping is prohibited to avoid replay collisions.`);
    }
    const fixture = fixtures[vuIndex];
    cachedDeviceId = fixture.deviceId;

    // Decode base64 PKCS#8 DER private key
    const pkcs8ArrayBuffer = encoding.b64decode(fixture.privateKeyPkcs8);
    cachedKey = await subtle.importKey(
      'pkcs8',
      pkcs8ArrayBuffer,
      {
        name: 'ECDSA',
        namedCurve: 'P-256',
      },
      false,
      ['sign'],
    );
  }

  // 2. Monotonically increasing sequence per VU iteration
  const iter = (exec.vu && typeof exec.vu.iterationInScenario === 'number')
    ? exec.vu.iterationInScenario
    : __ITER;
  const sequence = (baseSequence + BigInt(iter + 1)).toString(10);
  const timestamp = Date.now().toString(10);

  // 3. Assemble canonical payload: timestamp:sequence:METHOD:requestTarget:bodySha256
  const canonicalString = `${timestamp}:${sequence}:POST:${REQUEST_TARGET}:${BODY_HASH}`;
  const canonicalBytes = new TextEncoder().encode(canonicalString);

  // 4. ECDSA P-256 SHA-256 signature and measure signing latency
  const signStart = Date.now();
  const p1363Sig = await subtle.sign(
    {
      name: 'ECDSA',
      hash: { name: 'SHA-256' },
    },
    cachedKey,
    canonicalBytes,
  );
  signingMs.add(Date.now() - signStart);

  // 5. Verify exactly 64 bytes and convert P1363 signature to strict canonical DER ECDSA format
  const rawSig = new Uint8Array(p1363Sig);
  if (rawSig.byteLength !== 64) {
    throw new Error(`WebCrypto sign returned unexpected signature byte length: ${rawSig.byteLength} (expected 64)`);
  }
  const derSig = p1363ToDer(rawSig);
  const signatureB64 = encoding.b64encode(
    derSig.buffer.slice(derSig.byteOffset, derSig.byteOffset + derSig.byteLength),
  );

  // 6. Synchronous HTTP POST request bounded with 5s timeout
  const params = {
    headers: {
      'Content-Type': 'application/json',
      'X-Device-Id': cachedDeviceId,
      'X-Timestamp': timestamp,
      'X-Sequence': sequence,
      'X-Signature': signatureB64,
    },
    timeout: '5s',
  };

  const res = http.post(TARGET_URL, RAW_BODY, params);

  // 7. Track accepted vs rejected counts (only HTTP 200 counts towards throughput)
  const isAccepted = res.status === 200;
  if (isAccepted) {
    accepted.add(1);
  } else {
    rejected.add(1);
  }

  check(res, {
    'status is 200': (r) => r.status === 200,
  });
}

/**
 * Summary handler: outputs standard k6 JSON metrics containing p(95), p(99),
 * accepted, rejected, and signing_ms to stdout and writes to /results/summary.json.
 */
export function handleSummary(data) {
  const jsonOutput = JSON.stringify(data, null, 2);
  return {
    stdout: jsonOutput,
    '/results/summary.json': jsonOutput,
  };
}
