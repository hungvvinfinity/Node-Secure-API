import http from 'k6/http';
import { check } from 'k6';
import { SharedArray } from 'k6/data';
import exec from 'k6/execution';
import encoding from 'k6/encoding';
import crypto from 'k6/crypto';
import { Counter, Trend } from 'k6/metrics';

// WebCrypto Subtle API from globalThis.crypto (official k6 v2.3+)
const subtle = globalThis.crypto?.subtle;
if (!subtle) {
  throw new Error('globalThis.crypto.subtle is required in k6 runtime');
}

// Custom benchmark metrics
const accepted = new Counter('accepted');
const rejected = new Counter('rejected');
const signingMs = new Trend('signing_ms');

// Constant Arrival Rate Scenario configuration
